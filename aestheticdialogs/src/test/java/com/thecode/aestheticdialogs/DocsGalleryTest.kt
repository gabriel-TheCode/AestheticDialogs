    // --- Plumbing --------------------------------------------------------------

    private fun screen(name: String, dark: Boolean = false, content: @Composable () -> Unit) {
        composeRule.setContent {
            AestheticDialogsTheme(darkTheme = dark) {
                Box(
                    modifier = Modifier
                        .fillMaxSize()
                        .background(AestheticDialogsTheme.colors.surface.sunken),
                ) {
                    HostAppBackdrop()
                    content()
                }
            }
        }
        captureScreenRoboImage("$DOCS_IMAGES/$name.png", HALF_SCALE)
    }

    private fun banner(name: String, uiModel: @Composable () -> NotificationUiModel) {
        composeRule.setContent {
            AestheticDialogsTheme(darkTheme = false) {
                BannerStage {
                    AestheticNotification(uiModel = uiModel(), onSignal = {})
                }
            }
        }
        captureStage(name)
    }

    private fun captureStage(name: String) {
        composeRule.onNodeWithTag(STAGE_TAG)
            .captureRoboImage("$DOCS_IMAGES/$name.png", HALF_SCALE)
    }

    /**
     * The frame a banner is photographed in: the theme canvas plus one gutter of
     * padding, so the shadow is not clipped at the edge of the image.
     */
    @Composable
    private fun BannerStage(content: @Composable () -> Unit) {
        Box(
            modifier = Modifier
                .testTag(STAGE_TAG)
                .width(BANNER_STAGE_WIDTH)
                .wrapContentHeight()
                .background(AestheticDialogsTheme.colors.surface.sunken)
                .padding(AestheticSpacing.xl),
            contentAlignment = Alignment.Center,
        ) {
            content()
        }
    }

    /**
     * Undecorated blocks standing in for the application behind the dialog.
     *
     * A dialog photographed on an empty canvas hides the two things the frame is
     * responsible for — the scrim and the elevation — so the gallery puts
     * something behind it. It is deliberately abstract: an invented app screen
     * would say more about the screenshot than about the library.
     */
    @Composable
    private fun HostAppBackdrop() {
        val colors = AestheticDialogsTheme.colors
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(AestheticSpacing.xl),
            verticalArrangement = Arrangement.spacedBy(AestheticSpacing.lg),
        ) {
            Box(
                Modifier
                    .width(BACKDROP_TITLE_WIDTH)
                    .height(BACKDROP_TITLE_HEIGHT)
                    .background(colors.border.default, RoundedCornerShape(AestheticSpacing.sm)),
            )
            Spacer(Modifier.height(AestheticSpacing.sm))
            repeat(BACKDROP_ROWS) {
                Box(
                    Modifier
                        .fillMaxWidth()
                        .height(BACKDROP_ROW_HEIGHT)
                        .background(colors.border.subtle, RoundedCornerShape(AestheticSpacing.md)),
                )
            }
        }
    }

    /** Placeholder body for the rich-content dialog gallery entry. */
    @Composable
    private fun ConsentPlaceholder() {
        val colors = AestheticDialogsTheme.colors
        // The content dialog hands over an unpadded column on purpose, so the
        // gallery pads like any other caller. Rendering it flush to the surface
        // is what made the screenshot look misaligned against the header.
        Column(
            modifier = Modifier
                .fillMaxWidth()
                .padding(horizontal = AestheticSpacing.xxl),
            verticalArrangement = Arrangement.spacedBy(AestheticSpacing.md),
        ) {
            CONSENT_LINES.forEach { line ->
                Text(
                    text = line,
                    style = AestheticDialogsTheme.typography.message,
                    color = colors.content.secondary,
                )
            }
        }
    }

