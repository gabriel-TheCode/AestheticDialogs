/**
 * Renders the images the README shows.
 *
 * These are documentation assets, not baselines. They live here rather than in a
 * screen-recording workflow because a README screenshot that is produced by hand
 * is stale the day after it is taken: this one is regenerated by the same command
 * that records the visual baselines, so a padding change or a palette change
 * shows up in the documentation without anybody remembering to retake anything.
 *
 * ```
 * ./gradlew :aestheticdialogs:recordRoborazziDebug
 * ```
 *
 * Dialogs are captured as whole screens, because a dialog is a window over a
 * scrim and cropping it to the surface would hide half of what the component
 * does. Banners are captured as nodes, because they are ordinary composables and
 * a full screen of empty canvas around them shows nothing.
 */
